/*
 * Parallel-coordinate, pictorial-bar, dataset, data-transform and calendar examples carried over
 * from `parallel-simple.ts`, `parallel-aqi.ts`, the three `pictorialBar-*.ts` files, the five
 * `dataset-*.ts` files, the two `data-transform-*.ts` files and the seven `calendar-*.ts` files of
 * apache/echarts-examples.
 *
 * The pages keep the official ids, so the Kotlin/JS port and the JSON port of the same chart share
 * one route.
 *
 * Compacted on purpose, because the model has no field for them:
 *
 * - `AxisOption` has no `dim`: the `parallelAxis` entries rely on their order, which is the same
 *   dimension mapping for a fresh option, so every `dim` of `parallel-simple` and `parallel-aqi` is
 *   dropped;
 * - `CalendarLabelOption` has neither `firstDay` nor `nameMap`, so the Chinese day/month names and
 *   the Sunday-first weeks of `calendar-charts` and `calendar-pie` fall back to the ECharts
 *   defaults (English names, Monday first);
 * - `CalendarLabelOption` has no `formatter` either, so the `'{start} 1st'` / `'{start} 2nd'` year
 *   labels of `calendar-effectscatter` show the plain year;
 * - `EChartsColor` is a plain color, not a gradient, so the two `LinearGradient` fills of
 *   `pictorialBar-dotted` become solid colors: `#14c8d4` for the bars and a translucent
 *   `rgba(20, 200, 212, 0.2)` for the background bars;
 * - callback formatters become strings or are dropped: the `name: value` tooltip of
 *   `pictorialBar-velocity`, the `{dd}` label of `calendar-pie` and the percentage label of
 *   `pictorialBar-body-fill` are dropped, the last one therefore labels the raw water content;
 * - `MarkLineOption.symbol` is a list, so `symbol: 'none'` of `pictorialBar-body-fill` is written as
 *   `["none", "none"]`;
 * - the root-level `markLine: { z: -100 }` of `pictorialBar-body-fill` has no model field (only the
 *   series carry a `markLine`); it only shifted the draw order of the min/max lines, so dropping it
 *   does not change the picture;
 * - the `symbolSize` callbacks of `calendar-effectscatter` and `calendar-charts` are dropped as well,
 *   which leaves the default point size; `calendar-charts` keeps one `visualMap` with a `controller`
 *   object because `VisualMapOption.controller` is a raw `JsonElement`.
 *
 * `Math.random()` is replaced by [pseudoRandom], a fixed hash, so every page is reproducible. The
 * 31-day tables of `parallel-aqi` are kept in full. A calendar pie takes a date as its `center`;
 * because `SeriesOption.center` is a list, the date is written as a one-element array, which the
 * calendar coordinate system unwraps again (`dataToPoint` reads `data[0]`).
 */

