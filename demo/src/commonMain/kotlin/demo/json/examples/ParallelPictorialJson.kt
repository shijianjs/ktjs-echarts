/** Month lengths of a common year; February is adjusted by [daysInMonth]. */
private val MONTH_LENGTHS = intArrayOf(31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31)

/** Whether [year] is a leap year. */
private fun isLeapYear(year: Int): Boolean =
    year % 4 == 0 && (year % 100 != 0 || year % 400 == 0)

/** Number of days of [month] in [year]. */
private fun daysInMonth(year: Int, month: Int): Int =
    if (month == 2 && isLeapYear(year)) 29 else MONTH_LENGTHS[month - 1]

/** Number of days of [year]. */
private fun daysInYear(year: Int): Int = if (isLeapYear(year)) 366 else 365

/** Formats a date as the `yyyy-MM-dd` string a calendar accepts. */
private fun dateText(year: Int, month: Int, day: Int): String =
    "$year-${month.toString().padStart(2, '0')}-${day.toString().padStart(2, '0')}"

/** The date of the [dayOfYear]-th day (1-based) of [year]. */
private fun dateOf(year: Int, dayOfYear: Int): String {
    var remaining = dayOfYear
    var month = 1
    while (remaining > daysInMonth(year, month)) {
        remaining -= daysInMonth(year, month)
        month++
    }
    return dateText(year, month, remaining)
}

/**
 * A deterministic stand-in for `Math.random()`.
 *
 * Upstream generates the daily readings with `Math.floor(Math.random() * max)`; this hash keeps the
 * pages reproducible without a platform random source.
 */
private fun pseudoRandom(index: Int, seed: Int, max: Int): Int {
    var value = index * 1103515245 + seed * 12345 + 0x5DEECE6
    value = (value xor (value ushr 16)) * 0x45D9F3B
    value = value xor (value ushr 16)
    return (value and 0x7FFFFFFF) % max
}

/** One `date to value` reading per day of [year]. */
private fun dailyReadings(year: Int, max: Int, seed: Int): List<Pair<String, Int>> =
    List(daysInYear(year)) { index -> dateOf(year, index + 1) to pseudoRandom(index, seed, max) }

/** One `date to value` reading per day of [month]. */
private fun monthReadings(year: Int, month: Int, max: Int, seed: Int): List<Pair<String, Int>> {
    val firstDay = (1 until month).sumOf { daysInMonth(year, it) }
    return List(daysInMonth(year, month)) { index ->
        dateOf(year, firstDay + index + 1) to pseudoRandom(index, seed, max)
    }
}

/** The `[date, value]` rows a calendar heatmap or scatter expects. */
private fun entriesOf(readings: List<Pair<String, Int>>): List<DataValue> =
    readings.map { (date, value) -> timedValue(date, value) }

/** One row of `parallel-aqi`: the numeric dimensions followed by the air-quality label. */
private fun aqiRow(label: String, vararg values: Number): DataValue =
    DataValue.Array(values.map { valueOf(it) } + textValue(label))

/** One `{ source, target }` edge of a graph, addressing nodes by index. */
private fun indexLink(source: Int, target: Int): DataValue =
    objectValue(
        "source" to JsonPrimitive(source),
        "target" to JsonPrimitive(target),
    )

