/*
 * Tree data inlined from the assets the official examples load at runtime.
 *
 * `flare` is the tree of `public/data/asset/data/flare.json` of apache/echarts-examples; the
 * official `tree-*` examples fetch it with `$.get`, which this static site does not do. `flareTree`
 * builds a fresh node tree on every call so that each mounted chart owns its own data.
 */

/** One node of a tree; [value] is only set for the leaves. */
internal fun treeNode(
    name: String,
    value: Double? = null,
    vararg children: TreeSeriesNodeItemOption,
): TreeSeriesNodeItemOption =
    unsafeJso {
        this.name = OptionId(name)
        if (value != null) this.value = OptionDataValue(value)
        if (children.isNotEmpty()) this.children = Array(children.size) { children[it] }
    }

